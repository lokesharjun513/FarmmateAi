from enum import Enum


class WorkflowType(str, Enum):
    CROP_PLANNING = "CROP_PLANNING"
    DAILY_ASSISTANT = "DAILY_ASSISTANT"
    GENERAL_CHAT = "GENERAL_CHAT"
    DISEASE_ASSISTANT = "DISEASE_ASSISTANT"
    HARVEST_ASSISTANT = "HARVEST_ASSISTANT"


class WorkflowState(str, Enum):
    IDLE = "IDLE"

    SELECT_FARM = "SELECT_FARM"

    RECOMMEND_CROP = "RECOMMEND_CROP"

    SELECT_CROP = "SELECT_CROP"

    RECOMMEND_SOWING_DATE = "RECOMMEND_SOWING_DATE"

    CONFIRM_START = "CONFIRM_START"

    GENERATE_PLAN = "GENERATE_PLAN"

    ACTIVE = "ACTIVE"

    COMPLETED = "COMPLETED"

    CANCELLED = "CANCELLED"


class WorkflowStatus(str, Enum):
    ACTIVE = "ACTIVE"
    COMPLETED = "COMPLETED"
    CANCELLED = "CANCELLED"